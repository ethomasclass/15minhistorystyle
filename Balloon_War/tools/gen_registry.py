"""Write src/images.ts (pixel size of every image under public/img/chNN_*) and src/layers3d.ts (size + layer depths of
every 3D photo in public/img/layers3d/), so scenes can place pictures without reading files. Re-run after adding images
or regenerating layers:  python3 tools/gen_registry.py"""
import glob, json, os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); PUB = os.path.join(HERE, "..", "public")
sizes = {}
for f in sorted(glob.glob(os.path.join(PUB, "img", "ch*", "*"))):
    if f.lower().endswith((".jpg", ".jpeg", ".png", ".webp")):
        sizes[os.path.relpath(f, os.path.join(PUB, "img"))] = list(Image.open(f).size)
with open(os.path.join(HERE, "..", "src", "images.ts"), "w") as o:
    o.write("// Generated by tools/gen_registry.py: every archival image and its pixel size.\n")
    o.write("export const SIZES: Record<string, [number, number]> = " + json.dumps(sizes, indent=1) + ";\n")
    o.write("/** An image under public/img by its path, e.g. im('ch02_protector/x.jpg'). */\n")
    o.write("export const im = (p: string) => {\n  const size = SIZES[p];\n  if (!size) throw new Error(`No image ${p}`);\n  return {src: `img/${p}`, size};\n};\n")
l3 = {}
for f in sorted(glob.glob(os.path.join(PUB, "img", "layers3d", "*", "layers.json"))):
    d = json.load(open(f)); l3[os.path.basename(os.path.dirname(f))] = {"size": d["size"], "depths": [round(x, 3) for x in d["depth"]]}
with open(os.path.join(HERE, "..", "src", "layers3d.ts"), "w") as o:
    o.write("// Generated by tools/gen_registry.py from public/img/layers3d/*/layers.json (bash tools/layers3d_jobs.sh).\n")
    o.write("export const L3D: Record<string, {size: [number, number]; depths: number[]}> = " + json.dumps(l3) + ";\n")
print(len(sizes), "images,", len(l3), "3D photos")
