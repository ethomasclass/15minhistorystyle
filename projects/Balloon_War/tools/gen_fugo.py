"""Write src/fugo.ts from public/data/fugo_incidents.json (Mikesh 1973, appendix: 285 recorded incidents).
t = days since 1944-11-01 (recovery date, sorted); x/y on the Pacific map frame (same projection as src/pacific.ts).
Skips the misprinted No. 12 (no position) and No. 283 (off Japan, which would read as a landing in Asia).

  python3 tools/gen_fugo.py
"""
import datetime, json

D0 = datetime.date(1944, 11, 1)
proj = lambda lon, lat: (((lon + 360 if lon < 0 else lon) - 125.0) * 11.64, (76.0 - lat) * 15.2)
rows = json.load(open("public/data/fugo_incidents.json"))
out = []
for r in rows:
    if r.get("lat") is None or r.get("plot") is False or (r.get("outside_north_america") and r.get("region") != "Hawaii"):
        continue
    x, y = proj(r["lon"], r["lat"])
    t = (datetime.date.fromisoformat(r["date"]) - D0).days
    out.append(dict(t=t, x=round(x, 1), y=round(y, 1), region=r.get("region") or "", country=r.get("country") or "", kind=r.get("kind") or ""))
out.sort(key=lambda o: o["t"])
first, last = min(r["date"] for r in rows), max(r["date"] for r in rows)
with open("src/fugo.ts", "w") as f:
    f.write("// Generated by tools/gen_fugo.py from public/data/fugo_incidents.json (Mikesh 1973 appendix). Do not edit.\n")
    f.write("export type Incident = {t: number; x: number; y: number; region: string; country: string; kind: string};\n")
    f.write("export const INCIDENTS: Incident[] = [\n")
    for o in out:
        f.write("  " + json.dumps(o, separators=(",", ":")) + ",\n")
    f.write("];\n")
    f.write(f'export const FIRST = "{first}";\nexport const LAST = "{last}";\n')
print(f"{len(out)} incidents plotted, {first} to {last}, last day t={out[-1]['t']}")
