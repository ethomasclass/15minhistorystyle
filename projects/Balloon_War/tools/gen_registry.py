"""Write src/images.ts (pixel size of every image under public/img/chNN_*), so scenes can place pictures without reading files. Re-run after adding images
or regenerating layers:  python3 tools/gen_registry.py"""
import glob, json, os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); PUB = os.path.join(HERE, "..", "public")
sizes = {}
for f in sorted(glob.glob(os.path.join(PUB, "img", "ch*", "*"))):
    if f.lower().endswith((".jpg", ".jpeg", ".png", ".webp")):
        sizes[os.path.relpath(f, os.path.join(PUB, "img"))] = list(Image.open(f).size)
with open(os.path.join(HERE, "..", "src", "images.ts"), "w") as o:
    o.write("// Generated by tools/gen_registry.py: every archival image and its pixel size.\n")
    o.write("export const SIZES: Record<string, [number, number]> = " + json.dumps(sizes, indent=1) + ";\n")
    o.write("/** An image under public/img by its path, e.g. im('ch02_protector/x.jpg'). */\n")
    o.write("export const im = (p: string) => {\n  const size = SIZES[p];\n  if (!size) throw new Error(`No image ${p}`);\n  return {src: `img/${p}`, size};\n};\n")
