"""Write src/pacific.ts: Natural Earth land (public domain, public/data/ne_50m_land.geojson) projected onto a 1920x1080
Pacific-centred frame from Japan to the Great Lakes, as SVG path strings, plus the same projection for TypeScript.
  python3 tools/gen_pacific.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
LON0, LAT0, KX, KY = 125.0, 76.0, 11.64, 15.2      # x = (lon - 125) * 11.64 ; y = (76 - lat) * 15.2


def proj(lon, lat):
    if lon < 0: lon += 360
    return (lon - LON0) * KX, (LAT0 - lat) * KY


def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0
    n = (dx * dx + dy * dy) ** 0.5 or 1e-9
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x1 * y0 - y1 * x0) / n
        if d > dmax: dmax, idx = d, i
    if dmax > eps:
        return rdp(pts[:idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


d = json.load(open(os.path.join(HERE, "..", "public", "data", "ne_50m_land.geojson")))
paths = []
for f in d["features"]:
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        ring = poly[0]
        lons = [p[0] + 360 if p[0] < 0 else p[0] for p in ring]
        lats = [p[1] for p in ring]
        # keep rings in the window (allowing a margin), skip rings that wrap the antimeridian badly
        if max(lons) < 110 or min(lons) > 300 or max(lats) < 0 or min(lats) > 85: continue
        if max(lons) - min(lons) > 180: continue
        pr = [proj(*p) for p in ring]
        h = len(pr) // 2          # a closed ring: simplify its two halves (rdp needs distinct end points)
        pts = rdp(pr[:h + 1], 1.2)[:-1] + rdp(pr[h:], 1.2)
        if len(pts) < 4: continue
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if max(xs) < -50 or min(xs) > 1970 or max(ys) < -50 or min(ys) > 1130: continue
        if (max(xs) - min(xs)) * (max(ys) - min(ys)) < 40: continue
        paths.append("M" + " L".join(f"{x:.0f},{y:.0f}" for x, y in pts) + " Z")
out = os.path.join(HERE, "..", "src", "pacific.ts")
with open(out, "w") as o:
    o.write("// Generated by tools/gen_pacific.py from Natural Earth (public domain): land on a 1920x1080 Pacific-centred frame.\n")
    o.write(f"export const LAND = {json.dumps(' '.join(paths))};\n")
    o.write(f"/** lon/lat (degrees, west negative) to screen x/y on the same frame. */\n")
    o.write(f"export const proj = (lon: number, lat: number): [number, number] => [((lon < 0 ? lon + 360 : lon) - {LON0}) * {KX}, ({LAT0} - lat) * {KY}];\n")
print(len(paths), "rings,", os.path.getsize(out) // 1024, "KB")
